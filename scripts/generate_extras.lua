-- Returns the out-of-date file names. Check mode never opens an output for writing.
function M.write(check, directory)
    directory = directory or 'extra'
    local outputs, keys, changed = M.render(), {}, {}
    for key in pairs(outputs) do
        keys[#keys + 1] = key
    end
    table.sort(keys)
    for _, key in ipairs(keys) do
        local path, expected = directory .. '/' .. key, outputs[key]
        if read(path) ~= expected then
            changed[#changed + 1] = key
            if not check then
                local file = assert(io.open(path, 'wb'))
                local ok, err = file:write(expected)
                local closed, close_err = file:close()
                assert(ok, err)
                assert(closed, close_err)
            end
        end
    end
    return changed
end

function M.main(args)
    if #args > 1 or (args[1] and args[1] ~= '--check' and args[1] ~= '--help') then
        io.stderr:write 'Usage: lua scripts/generate_extras.lua [--check]\n'
        return 2
    end
    if args[1] == '--help' then
        io.write 'Usage: lua scripts/generate_extras.lua [--check]\nRun from the repository root; --check reports drift without writing.\n'
        return 0
    end
    local ok, changed = pcall(M.write, args[1] == '--check')
    if not ok then
        io.stderr:write(tostring(changed) .. '\n')
        return 1
    end
    for _, key in ipairs(changed) do
        io.write((args[1] == '--check' and 'OUT OF DATE ' or 'WROTE ') .. 'extra/' .. key .. '\n')
    end
    if args[1] == '--check' and #changed > 0 then return 1 end
    io.write 'Extras are up to date.\n'
    return 0
end

if arg and arg[0] and arg[0]:match 'generate_extras%.lua$' then os.exit(M.main(arg)) end
return M
