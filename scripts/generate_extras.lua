-- Run from the repository root: lua scripts/generate_extras.lua [--check]
-- Also usable via dofile() in headless Neovim tests. No user configuration or callbacks.
local M = {}
local names = { 'black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white' }
local banner = '# Generated by scripts/generate_extras.lua; do not edit.\n'
local function text(lines) return table.concat(lines, '\n') .. '\n' end
local function quoted(value) return string.format('%q', value) end
local function append(lines, key, value) lines[#lines + 1] = key .. ' = ' .. quoted(value) end
local function read(path)
    local file = io.open(path, 'rb')
    if not file then return nil end
    local content = file:read '*a'
    assert(file:close())
    return content
end

